from odoo import api, fields, models
from odoo.exceptions import UserError, ValidationError
from odoo.tools import _


class HeatBillLine(models.Model):
    """Keep the frozen calculation result for one physical supply object."""

    _name = "heat.bill.line"
    _description = "Heat Bill Line"
    _order = "bill_id, sequence, id"
    _check_company_auto = True
    _rec_name = "supply_object_id"

    bill_id = fields.Many2one("heat.bill", required=True, ondelete="cascade", check_company=True)
    sequence = fields.Integer(default=10)
    supply_object_id = fields.Many2one(
        "heat.supply.object", required=True, ondelete="restrict", check_company=True
    )
    node_id = fields.Many2one(
        "heat.supply.node", required=True, ondelete="restrict", check_company=True
    )
    actual_consumer_id = fields.Many2one("res.partner", required=True, ondelete="restrict")
    billing_consumer_id = fields.Many2one("res.partner", required=True, ondelete="restrict")
    calculation_method = fields.Selection(
        [("meter", "Meter"), ("volume", "Heated Volume")], required=True
    )
    source_meter_id = fields.Many2one(
        "heat.meter", required=True, ondelete="restrict", check_company=True
    )
    start_reading_id = fields.Many2one(
        "heat.meter.reading", ondelete="set null", check_company=True
    )
    end_reading_id = fields.Many2one("heat.meter.reading", ondelete="set null", check_company=True)
    heated_volume_m3 = fields.Float(digits=(16, 6))
    allocation_share = fields.Float(digits=(16, 12))
    quantity_gcal = fields.Float(required=True, digits=(16, 6))
    category_id = fields.Many2one("heat.consumer.category", required=True, ondelete="restrict")
    tariff_id = fields.Many2one(
        "heat.tariff", required=True, ondelete="restrict", check_company=True
    )
    price_unit = fields.Monetary(required=True)
    subtotal = fields.Monetary(compute="_compute_subtotal", store=True)
    currency_id = fields.Many2one(related="bill_id.currency_id", store=True)
    company_id = fields.Many2one(related="bill_id.company_id", store=True, index=True)

    period_start = fields.Date(related="bill_id.period_start", store=True)
    bill_state = fields.Selection(related="bill_id.state", store=True)
    _object_month_unique = models.UniqueIndex(
        "(supply_object_id, company_id, period_start) WHERE bill_state != 'cancelled'",
        "A supply object can be billed only once per company and month.",
    )

    _object_unique = models.Constraint(
        "UNIQUE(bill_id, supply_object_id)", "An object can occur only once in a heat bill."
    )
    _positive_values = models.Constraint(
        "CHECK(quantity_gcal >= 0 AND price_unit > 0 AND heated_volume_m3 > 0 AND allocation_share >= 0 AND allocation_share <= 1)",
        "Heat quantities and allocation shares must be valid and prices/volumes positive.",
    )

    @api.depends("quantity_gcal", "price_unit", "currency_id")
    def _compute_subtotal(self):
        """Calculate this object's charge using the bill currency's rounding."""
        for line in self:
            line.subtotal = line.currency_id.round(line.quantity_gcal * line.price_unit)

    @api.constrains("bill_id", "billing_consumer_id")
    def _check_payer(self):
        """Reject a line if it was attached to somebody else's bill."""
        for line in self:
            if line.billing_consumer_id != line.bill_id.consumer_id:
                raise ValidationError(_("The line payer must match the bill consumer."))

    @api.model_create_multi
    def create(self, vals_list):
        """Refuse manual lines because only the calculation may create them."""
        raise UserError(_("Bill lines are generated by Calculate and cannot be entered manually."))

    def write(self, vals):
        """Keep calculated quantities and prices unchanged, including over RPC."""
        raise UserError(_("Calculated bill lines cannot be edited manually."))

    def unlink(self):
        """Allow line removal only through the bill's controlled reset path."""
        if self.env.su and self.env.context.get("_force_unlink"):
            return super().unlink()
        raise UserError(_("Calculated bill lines cannot be deleted manually."))

    @api.model
    def _create_snapshots(self, vals_list):
        """Insert lines prepared by the trusted server-side calculation."""
        self.flush_model(["bill_state", "company_id", "period_start"])
        return super().create(vals_list)

    def _clear_snapshots(self):
        """Remove old lines after the parent bill has approved the reset."""
        return super().unlink()
